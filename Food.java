public class Food {
    public int xpos;
    public int ypos;
    
    public Food()
    {
    }
    public int getXPos()
    {
        return xpos;
    }
    public int getYPos()
    {
        return ypos;
    }
    public void setPos(int x, int y)
    {
        this.xpos = x;
        this.ypos = y;
    }
}
